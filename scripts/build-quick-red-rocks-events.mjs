import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const EXPLICIT_YEAR = process.argv[2] ? Number(process.argv[2]) : null;
const EVENTS_DIR = path.join(ROOT, "data", "snapshots", "events");
const OUT_FILE = path.join(ROOT, "data", "red-rocks-events.ts");

function toDate(value) {
  if (!value || typeof value !== "string") return null;
  const normalized = value.includes("T") ? value : `${value}T00:00:00`;
  const date = new Date(normalized);
  return Number.isNaN(date.getTime()) ? null : date;
}

function formatDateLabel(isoDate) {
  const date = toDate(isoDate);
  if (!date) return isoDate;
  return date.toLocaleDateString("en-US", {
    weekday: "long",
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "America/Denver",
  });
}

function formatTime(startLocal) {
  const date = toDate(startLocal);
  if (!date) return "TBD";
  return date.toLocaleTimeString("en-US", {
    hour: "numeric",
    minute: "2-digit",
    hour12: true,
    timeZone: "America/Denver",
  });
}

function normalizeSupport(event) {
  const names = Array.isArray(event.artistNames) ? event.artistNames.filter(Boolean) : [];
  if (names.length <= 1) return "Lineup to be announced";
  return names.slice(1).join(", ");
}

async function discoverSnapshotYears() {
  const files = await fs.readdir(EVENTS_DIR);
  const years = files
    .map((name) => name.match(/^redrocks-(\d{4})\.json$/)?.[1])
    .filter(Boolean)
    .map(Number)
    .sort((a, b) => a - b);
  return years.length ? years : [2026];
}

async function main() {
  const years = EXPLICIT_YEAR ? [EXPLICIT_YEAR] : await discoverSnapshotYears();
  const events = [];
  for (const targetYear of years) {
    const raw = await fs.readFile(path.join(EVENTS_DIR, `redrocks-${targetYear}.json`), "utf8");
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed?.events)) {
      events.push(...parsed.events);
    }
  }

  const normalized = events
    .filter((event) => event && typeof event === "object")
    .filter((event) => typeof event.dateKey === "string" && /^\d{4}-\d{2}-\d{2}$/.test(event.dateKey))
    .map((event) => ({
      isoDate: event.dateKey,
      formattedDate: formatDateLabel(event.dateKey),
      artist: typeof event.name === "string" && event.name.trim() ? event.name.trim() : "TBD Event",
      support: normalizeSupport(event),
      time: formatTime(event.startLocal || event.startAt),
    }))
    .sort((a, b) => {
      const byDate = a.isoDate.localeCompare(b.isoDate);
      if (byDate !== 0) return byDate;
      return a.artist.localeCompare(b.artist);
    });

  const sourceLabel = years.map((y) => `data/snapshots/events/redrocks-${y}.json`).join(", ");
  const file = `export type RedRocksShow = {\n  isoDate: string;\n  formattedDate: string;\n  artist: string;\n  support: string;\n  time: string;\n};\n\n// Auto-generated by scripts/build-quick-red-rocks-events.mjs\n// Source: ${sourceLabel}\nexport const upcomingRedRocksShows: RedRocksShow[] = ${JSON.stringify(normalized, null, 2)} as const;\n`;

  await fs.writeFile(OUT_FILE, file, "utf8");
  console.log(`Built quick Red Rocks events: ${normalized.length} entries across [${years.join(", ")}].`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
